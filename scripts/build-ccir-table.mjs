#!/usr/bin/env node
// Builds src/shared/constants/ccir-chronicity.generated.ts from the AHRQ HCUP
// Chronic Condition Indicator Refined (CCIR) for ICD-10-CM CSV.
//
//   1. Download the latest zip from
//      https://hcup-us.ahrq.gov/toolssoftware/chronic_icd10/chronic_icd10.jsp
//   2. node scripts/build-ccir-table.mjs path/to/CCIR_vYYYY-N.csv
//
// The CSV assigns every ICD-10-CM code 1 (chronic), 0 (not chronic) or
// 9 (no determination). ~75k rows collapse to a few thousand prefixes: a
// prefix is written when every code under it shares one value and its parent
// does not, so a longest-prefix lookup finds exactly one entry per code.

import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const csvPath = process.argv[2]
if (!csvPath) {
  console.error('usage: node scripts/build-ccir-table.mjs <CCIR_vYYYY-N.csv>')
  process.exit(1)
}

const lines = readFileSync(csvPath, 'utf8').replace(/^\uFEFF/, '').split(/\r?\n/)
const version = /Chronic Condition Indicator Refined (v\d{4}\.\d+)/.exec(lines[0] ?? '')?.[1]
if (!version) throw new Error(`No CCIR version in the first line: ${lines[0]}`)

// Rows look like: 'A000',"Cholera due to Vibrio cholerae 01, biovar cholerae",0
// (a few codes carry a trailing space inside the quotes: 'D57454 ').
const byCode = new Map()
for (const line of lines) {
  const m = /^'([A-Z0-9]+) *',.*,([019])\s*$/.exec(line)
  if (m) byCode.set(m[1], m[2])
}
if (byCode.size < 50_000) throw new Error(`Only ${byCode.size} codes parsed — CSV layout changed?`)

const valuesUnder = new Map()
for (const [code, value] of byCode) {
  for (let i = 1; i <= code.length; i++) {
    const prefix = code.slice(0, i)
    if (!valuesUnder.has(prefix)) valuesUnder.set(prefix, new Set())
    valuesUnder.get(prefix).add(value)
  }
}

const buckets = { 1: [], 0: [], 9: [] }
for (const [prefix, values] of valuesUnder) {
  if (values.size !== 1) continue
  if (prefix.length > 1 && valuesUnder.get(prefix.slice(0, -1)).size === 1) continue
  buckets[[...values][0]].push(prefix)
}
for (const list of Object.values(buckets)) list.sort()

const out = `// Generated by scripts/build-ccir-table.mjs from CCIR ${version} — do not edit.
//
// Source: Chronic Condition Indicator Refined for ICD-10-CM. Healthcare Cost and
// Utilization Project (HCUP). Agency for Healthcare Research and Quality,
// Rockville, MD. https://hcup-us.ahrq.gov/toolssoftware/chronic_icd10/chronic_icd10.jsp
//
// Comma-separated ICD-10-CM prefixes (upper-case, no dot), one list per value.
// ${byCode.size} codes → ${buckets[1].length + buckets[0].length + buckets[9].length} prefixes.

export const CCIR_VERSION = '${version}'

export const CCIR_PREFIXES = {
  chronic: '${buckets[1].join(',')}',
  nonChronic: '${buckets[0].join(',')}',
  undetermined: '${buckets[9].join(',')}',
} as const
`

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const target = path.join(root, 'src/shared/constants/ccir-chronicity.generated.ts')
writeFileSync(target, out)
console.log(
  `${version}: ${byCode.size} codes → chronic ${buckets[1].length}, not chronic ${buckets[0].length}, ` +
    `no determination ${buckets[9].length} prefixes (${out.length} bytes) → ${path.relative(root, target)}`,
)
